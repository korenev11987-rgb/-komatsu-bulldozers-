import type { NodeId, NodeInfo, Part } from '../types';

/**
 * Общий «каркас» описаний узлов. Модельные файлы передают сюда
 * характерные для конкретной машины сведения, а при необходимости
 * полностью переопределяют отдельные узлы.
 * Номера деталей намеренно не приводятся — используйте каталог запчастей Komatsu.
 */
export interface NodeParams {
  modelName: string;
  engine: { model: string; layout: string; displacement: string; power: string; extraParts?: Part[]; note?: string };
  cooling: { note: string };
  undercarriage: {
    shoes: string;
    trackRollers: number;
    carrierRollers: number;
    suspension: string;
    note?: string;
  };
  torqueConverter: { description: string };
  gearbox: { description: string };
  steering: 'hss' | 'clutch';
  finalDrive: { description: string };
  pumps: { description: string; parts: Part[] };
  blade: { description: string; variants: string; note?: string };
  ripper: { description: string; variants: string; note?: string };
  electrics: ElectricsParams;
  overrides?: Partial<Record<NodeId, Partial<NodeInfo>>>;
}

type ElectricNodeId = 'batteries' | 'alternator' | 'starter' | 'wiring' | 'fuseBox' | 'controllers' | 'lights' | 'monitor';

export interface ElectricsParams {
  /** Классическая электрика без электронных блоков управления (D355A) */
  classic: boolean;
  batteries: string;
  alternator: string;
  starter: string;
  controllers: { title: string; description: string; parts: Part[] };
  monitor: { title: string; description: string; parts: Part[] };
  lights: string;
}

